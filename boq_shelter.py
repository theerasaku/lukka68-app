CONTINGENCY_PCT = 0.05   # 5%
VAT_PCT = 0.07           # 7%


def build_boq_df():
    """สร้าง DataFrame รายการ BOQ ทั้งหมด"""
    rows = []
    for sec_code, sec_name, items in SECTIONS:
        for rcode, name, unit, qty, unit_price, remark in items:
            rows.append({
                "หมวด": sec_code,
                "รหัส": rcode,
                "รายการ": name,
                "หน่วย": unit,
                "ปริมาณ": qty,
                "ราคาต่อหน่วย": unit_price,
                "จำนวนเงิน": round(qty * unit_price, 2),
                "หมายเหตุ": remark,
            })
    return pd.DataFrame(rows)


def compute_summary(df: pd.DataFrame):
    """คำนวณยอดรวมแต่ละหมวด และยอดรวมทั้งสิ้น"""
    section_totals = df.groupby("หมวด")["จำนวนเงิน"].sum()
    subtotal = df["จำนวนเงิน"].sum()
    contingency = round(subtotal * CONTINGENCY_PCT, 2)
    before_vat = round(subtotal + contingency, 2)
    vat = round(before_vat * VAT_PCT, 2)
    grand_total = round(before_vat + vat, 2)
    return section_totals, subtotal, contingency, before_vat, vat, grand_total
